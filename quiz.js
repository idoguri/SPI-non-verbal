let currentQuestionIndex = 0;
let score = 0;
let selectedQuestions = [];
let userAnswers = [];


// ======================================
// クイズ開始
// ======================================

function startQuiz() {
    document.getElementById("startButton").style.display = "none";
    document.getElementById("header").style.display = "block";
    document.getElementById("quizContainer").style.display = "block";

    // 100問からランダムで10問選ぶ
    selectedQuestions = getRandomQuestions(10);

    currentQuestionIndex = 0;
    score = 0;
    userAnswers = [];

    // 今回の10問における正解位置を決める
    // ①～④ができるだけ均等になるようにする
    assignAnswerPositions(selectedQuestions);

    displayQuestion();
}


// ======================================
// 問題をランダムに10問選ぶ
// ======================================

function getRandomQuestions(num) {
    const shuffled = [...allQuestions];

    // Fisher-Yatesシャッフル
    for (let i = shuffled.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));

        [shuffled[i], shuffled[j]] =
            [shuffled[j], shuffled[i]];
    }

    return shuffled.slice(0, num);
}


// ======================================
// 正解位置を決める
// ======================================
//
// 10問の場合、①～④を
// 3・3・2・2問ずつに分散させる。
// ただし、その順番は毎回ランダム。
// ======================================

function assignAnswerPositions(questions) {

    const positions = [];

    // 10問なら
    // ①：3問
    // ②：3問
    // ③：2問
    // ④：2問
    positions.push(1, 1, 1);
    positions.push(2, 2, 2);
    positions.push(3, 3);
    positions.push(4, 4);

    // 正解位置そのものをシャッフル
    for (let i = positions.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));

        [positions[i], positions[j]] =
            [positions[j], positions[i]];
    }

    // 各問題に正解位置を割り当てる
    questions.forEach((question, index) => {
        question.answerPosition = positions[index];
    });
}


// ======================================
// 問題を表示
// ======================================

function displayQuestion() {

    const questionObj =
        selectedQuestions[currentQuestionIndex];

    // 問題文を表示
    document.getElementById("questionText").textContent =
        questionObj.question;

    const optionsDiv =
        document.getElementById("options");

    // 以前の選択肢を削除
    optionsDiv.innerHTML = "";


    // ======================================
    // 選択肢を作成
    // ======================================

    const shuffledOptions = createShuffledOptions(questionObj);


    // ======================================
    // 選択肢ボタンを作成
    // ======================================

    shuffledOptions.forEach((option, index) => {

        const button = document.createElement("button");

        button.textContent =
            `${index + 1}. ${option}`;

        button.classList.add("optionButton");

        button.onclick = () =>
            checkAnswer(option);

        optionsDiv.appendChild(button);
    });
}


// ======================================
// 選択肢を作成
// ======================================
//
// 正解は指定された位置に配置し、
// 不正解の3つはランダムに並べる。
// ======================================

function createShuffledOptions(questionObj) {

    const correctAnswer = questionObj.answer;

    // 正解以外の選択肢を取得
    const wrongOptions =
        questionObj.options.filter(
            option => option !== correctAnswer
        );

    // 不正解の選択肢をシャッフル
    for (let i = wrongOptions.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));

        [wrongOptions[i], wrongOptions[j]] =
            [wrongOptions[j], wrongOptions[i]];
    }


    // 4つの空欄を作る
    const result = new Array(4);

    // 正解を指定された位置に配置
    result[questionObj.answerPosition - 1] =
        correctAnswer;


    // 残りの位置に不正解を配置
    let wrongIndex = 0;

    for (let i = 0; i < result.length; i++) {

        if (result[i] === undefined) {
            result[i] = wrongOptions[wrongIndex];
            wrongIndex++;
        }
    }

    return result;
}


// ======================================
// 正解判定
// ======================================

function checkAnswer(selectedOption) {

    const questionObj =
        selectedQuestions[currentQuestionIndex];


    // ユーザーの回答を記録
    userAnswers.push({
        question: questionObj.question,
        selectedAnswer: selectedOption,
        correctAnswer: questionObj.answer
    });


    // 正解なら得点
    if (selectedOption === questionObj.answer) {
        score++;
    }


    // 次の問題へ
    currentQuestionIndex++;


    if (currentQuestionIndex < selectedQuestions.length) {

        displayQuestion();

    } else {

        showResult();

    }
}


// ======================================
// 結果表示
// ======================================

function showResult() {

    const totalQuestions =
        selectedQuestions.length;


    document.getElementById("quizContainer")
        .style.display = "none";

    document.getElementById("resultContainer")
        .style.display = "block";

    document.getElementById("header")
        .style.display = "none";


    // ======================================
    // 各問題の結果
    // ======================================

    const resultHtml =
        userAnswers.map((answer, index) => {

            const isCorrect =
                answer.selectedAnswer ===
                answer.correctAnswer;


            return `
                <div>
                    <p>
                        <strong>第${index + 1}問</strong>
                    </p>

                    <p>
                        <strong>問題:</strong>
                        ${answer.question}
                    </p>

                    <p>
                        <strong>結果:</strong>
                        ${isCorrect ? "⭕️ 正解" : "❌ 不正解"}
                    </p>

                    <p>
                        <strong>あなたの解答:</strong>
                        ${answer.selectedAnswer}
                    </p>

                    <p>
                        <strong>正答:</strong>
                        ${answer.correctAnswer}
                    </p>
                </div>
            `;

        }).join("");


    document.getElementById("resultList")
        .innerHTML = resultHtml;


    // 得点表示
    document.getElementById("score")
        .innerText =
        `得点: ${score} / ${totalQuestions}`;
}


// ======================================
// 再挑戦
// ======================================

function restartQuiz() {

    document.getElementById("resultContainer")
        .style.display = "none";

    startQuiz();
}